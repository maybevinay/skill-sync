CREATE TABLE skills (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(80)  NOT NULL UNIQUE,
    category    VARCHAR(80)  NOT NULL,
    description VARCHAR(400) NOT NULL
);

CREATE TABLE profiles (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT       NOT NULL UNIQUE,
    full_name        VARCHAR(120) NOT NULL,
    photo_url        VARCHAR(500) NULL,
    bio              VARCHAR(800) NULL,
    learning_goals   VARCHAR(500) NULL,
    experience_years INT          NOT NULL DEFAULT 0,
    availability     VARCHAR(80)  NOT NULL DEFAULT 'WEEKNIGHTS',
    country          VARCHAR(80)  NULL,
    linkedin_url     VARCHAR(300) NULL,
    github_url       VARCHAR(300) NULL,
    portfolio_url    VARCHAR(300) NULL,
    created_at       TIMESTAMP    NOT NULL,
    updated_at       TIMESTAMP    NOT NULL
);

CREATE TABLE profile_skills (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_id   BIGINT      NOT NULL,
    skill_id     BIGINT      NOT NULL,
    level        VARCHAR(32) NOT NULL,
    progress     INT         NOT NULL DEFAULT 0,
    CONSTRAINT uk_profile_skill UNIQUE (profile_id, skill_id),
    CONSTRAINT fk_ps_profile FOREIGN KEY (profile_id) REFERENCES profiles (id) ON DELETE CASCADE,
    CONSTRAINT fk_ps_skill FOREIGN KEY (skill_id) REFERENCES skills (id)
);

CREATE TABLE mentor_profiles (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_id       BIGINT        NOT NULL UNIQUE,
    headline         VARCHAR(160)  NOT NULL,
    rating           DECIMAL(3,2)  NOT NULL DEFAULT 0,
    review_count     INT           NOT NULL DEFAULT 0,
    accepting        BOOLEAN       NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_mp_profile FOREIGN KEY (profile_id) REFERENCES profiles (id) ON DELETE CASCADE
);

CREATE TABLE match_requests (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    learner_id  BIGINT       NOT NULL,
    mentor_id   BIGINT       NOT NULL,
    message     VARCHAR(600) NOT NULL,
    status      VARCHAR(32)  NOT NULL,
    created_at  TIMESTAMP    NOT NULL,
    CONSTRAINT fk_req_learner FOREIGN KEY (learner_id) REFERENCES profiles (id),
    CONSTRAINT fk_req_mentor FOREIGN KEY (mentor_id) REFERENCES mentor_profiles (id)
);

CREATE TABLE reviews (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id  BIGINT       NOT NULL UNIQUE,
    reviewer_id BIGINT       NOT NULL,
    mentor_id   BIGINT       NOT NULL,
    rating      INT          NOT NULL,
    comment     VARCHAR(600) NOT NULL,
    created_at  TIMESTAMP    NOT NULL,
    CONSTRAINT fk_rev_req FOREIGN KEY (request_id) REFERENCES match_requests (id),
    CONSTRAINT fk_rev_reviewer FOREIGN KEY (reviewer_id) REFERENCES profiles (id),
    CONSTRAINT fk_rev_mentor FOREIGN KEY (mentor_id) REFERENCES mentor_profiles (id)
);
